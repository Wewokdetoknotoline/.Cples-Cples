parse_kk() {
    local kk="$1"
    [[ ! "$kk" =~ ^[0-9]{16}$ ]] && { echo "KK tidak valid"; return 1; }

    local kw="${kk:0:6}" kp="${kk:0:2}" kk4="${kk:0:4}" kc="${kk:4:2}" nu="${kk:6:10}"
    local p="${prov[$kp]:-Tidak dikenal}"
    local d="${kab[$kk4]:-Kab/Kota tidak dikenal, $p}"

    echo "Nomor KK       : $kk"
    echo "Kode Provinsi  : $kp"
    echo "Provinsi       : ${p^^}"
    echo "Kode Kab/Kota  : $kk4"
    echo "Kab/Kota       : $d"
    echo "Kode Kecamatan : $kc"
    echo "Nomor Urut     : $nu"
    echo "Jumlah Digit   : ${#kk}"
    echo "Reverse KK     : $(echo "$kk" | rev)"
}

read -rp "KK: " kk
